#include "EffectPacketSend.h"

#include "Packet.h"
#include "Player.h"
#include "Zone.h"

//////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////
EffectPacketSend::EffectPacketSend(Zone* pZone, ZoneCoord_t X, ZoneCoord_t Y) {
    m_pZone = pZone;
    m_X = X;
    m_Y = Y;
}

void EffectPacketSend::unaffect()

{
    Assert(m_pZone != NULL);
    Assert(m_pPacket != NULL);
    m_pZone->broadcastPacket(m_X, m_Y, m_pPacket);

    SAFE_DELETE(m_pPacket);
}

//////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////
string EffectPacketSend::toString() const {
    StringStream msg;
    msg << "EffectPacketSend(" << "ObjectID:" << getObjectID() << ", Packet : " << m_pPacket->toString() << ")";
    return msg.toString();
}
