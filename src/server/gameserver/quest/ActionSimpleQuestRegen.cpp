ActionSimpleQuestRegen::ActionSimpleQuestRegen()

{
    m_Period.tv_sec = 0;
    m_Period.tv_usec = 0;
    m_NextRegen.tv_sec = 0;
    m_NextRegen.tv_usec = 0;
}

