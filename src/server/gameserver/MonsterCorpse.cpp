//////////////////////////////////////////////////////////////////////////////
// get debug string
//////////////////////////////////////////////////////////////////////////////
string MonsterCorpse::toString() const {
    StringStream msg;
    msg << "MonsterCorpse(" << "ObjectID:" << (int)m_ObjectID << ",MonsterName:" << m_Name
        << ",MonsterType:" << (int)m_MonsterType << ",m_Dir:" << dir2String(m_Dir) << ")";
    return msg.toString();
}
