//////////////////////////////////////////////////////////////////////////////
// Given a monster object as the parameter, stores the monster's type, coordinates
// and direction, then carries over the items held in the monster's inventory.
//////////////////////////////////////////////////////////////////////////////
MonsterCorpse::MonsterCorpse(Monster* pMonster)

{
    Assert(pMonster != NULL);

    m_MonsterType = pMonster->getMonsterType();
    m_Name = pMonster->getName();
    m_Dir = pMonster->getDir();
    m_bhasHead = true;

    m_bShrine = false;

    setObjectID(pMonster->getObjectID());

    m_HostPartyID = 0;
}

MonsterCorpse::MonsterCorpse(MonsterType_t MType, const string& name, Dir_t dir)

{
    m_MonsterType = MType;
    m_Name = name;
    m_Dir = dir;
    m_bhasHead = true;

    m_bShrine = false;

    m_HostPartyID = 0;
}

