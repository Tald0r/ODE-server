#include "EffectAirShield.h"

#include "GCRemoveEffect.h"
#include "Monster.h"
#include "Slayer.h"
#include "Vampire.h"

//////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////
EffectAirShield::EffectAirShield(Creature* pCreature)

{
    Assert(pCreature != NULL);
    Assert(pCreature->isSlayer());

    setTarget(pCreature);
}

//////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////
void EffectAirShield::affect(Creature* pCreature)

{}

//////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////
void EffectAirShield::affect(Zone* pZone, ZoneCoord_t x, ZoneCoord_t y, Object* pObject)

{}

//////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////
void EffectAirShield::unaffect(Creature* pCreature)

{
    Assert(pCreature != NULL);
    Assert(pCreature->isSlayer());

    // Turns off the flag.
    pCreature->removeFlag(Effect::EFFECT_CLASS_AIR_SHIELD_1);

    Zone* pZone = pCreature->getZone();
    Assert(pZone != NULL);

    // Tells clients to remove the effect.
    GCRemoveEffect gcRemoveEffect;
    gcRemoveEffect.setObjectID(pCreature->getObjectID());
    gcRemoveEffect.addEffectList(m_ClientEffectClass);
    pZone->broadcastPacket(pCreature->getX(), pCreature->getY(), &gcRemoveEffect);
}

//////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////
void EffectAirShield::unaffect()

{
    Creature* pCreature = dynamic_cast<Creature*>(m_pTarget);
    unaffect(pCreature);
}

//////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////
void EffectAirShield::unaffect(Zone* pZone, ZoneCoord_t x, ZoneCoord_t y, Object* pObject)

{}

//////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////
void EffectAirShield::setLevel(Level_t Level) {
    m_Level = Level;

    if (Level <= GRADE_ADEPT_LIMIT_LEVEL)
        m_ClientEffectClass = EFFECT_CLASS_AIR_SHIELD_1;
    else if (Level <= GRADE_EXPERT_LIMIT_LEVEL)
        m_ClientEffectClass = EFFECT_CLASS_AIR_SHIELD_2;
    else if (Level <= GRADE_MASTER_LIMIT_LEVEL)
        m_ClientEffectClass = EFFECT_CLASS_AIR_SHIELD_3;
    else
        m_ClientEffectClass = EFFECT_CLASS_AIR_SHIELD_4;
}

//////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////
string EffectAirShield::toString() const {
    StringStream msg;
    msg << "EffectAirShield(" << "ObjectID:" << getObjectID() << ",Level:" << m_Level
        << ",ClientEffectClass:" << (int)m_ClientEffectClass << ",Damage:" << m_Damage << ")";
    return msg.toString();
}
