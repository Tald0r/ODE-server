string EffectMindControl::toString() const {
    StringStream msg;

    msg << "EffectMindControl(" << "ObjectID:" << getObjectID() << ",ToHit:" << m_ToHitBonus
        << ",Defense:" << m_DefenseBonus << ")";

    return msg.toString();
}
