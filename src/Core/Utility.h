//////////////////////////////////////////////////////////////////////////////
// Pick a random number
//////////////////////////////////////////////////////////////////////////////
inline int Random(int Min, int Max) {
    if (Max == 0 || Min > Max)
        return 0;
    return ((rand() % (int)((Max) - (Min) + 1)) + (Min));
}


//////////////////////////////////////////////////////////////////////////////
// Round off
//////////////////////////////////////////////////////////////////////////////
inline int Round(float f) {
    return f - 0.5 > (int)f ? (int)f + 1 : (int)f;
}

//////////////////////////////////////////////////////////////////////////////
// Dice function
//////////////////////////////////////////////////////////////////////////////
inline uint Dice(uint num, uint dice) {
    uint result = 0;
    for (uint i = 0; i < num; i++)
        result += rand() % dice + 1;
    return result;
}


