//////////////////////////////////////////////////////////////////////////////
// Rectangle class
//////////////////////////////////////////////////////////////////////////////
class VSRect {
public:
    VSRect(int l = 0, int t = 0, int r = 0, int b = 0) {
        left = l;
        top = t;
        right = r;
        bottom = b;
    }

    bool ptInRect(const POINT& pt) const {
        if (left <= pt.x && pt.x <= right && top <= pt.y && pt.y <= bottom)
            return true;
        return false;
    }

    bool ptInRect(const int x, const int y) const {
        if (left <= x && x <= right && top <= y && y <= bottom)
            return true;
        return false;
    }

    void set(int l, int t, int r, int b) {
        left = l;
        top = t;
        right = r;
        bottom = b;
    }


public:
    int left;
    int top;
    int right;
    int bottom;
};

